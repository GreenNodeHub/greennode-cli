package login

import (
	"fmt"
	"net/url"
)

// extractIdpHint pulls the identity-provider selector (the `idpId` query param)
// from a user-supplied SSO/IdP login link, returning it as the IdP hint the
// authorize flow forwards to IAM (so the provider-picker screen is skipped).
//
// The SSO model is "pkce + an IdP hint": the CLI does NOT use the pasted link as
// the authorize URL. It runs the SAME canonical IAM authorize flow pkce uses
// (https://signin.vngcloud.vn/ap/auth, loopback redirectUri, baked clientId, PKCE
// challenge + nonce), carrying only the link's idpId across as a hint. The link's
// host/path/redirectUri/clientId/codeChallenge/etc. are all DISCARDED — they are
// regenerated by the normal authorize path; only the IdP selector is preserved.
//
// This is why a console SSO deep-link (dashboard.console.vngcloud.vn/login
// ?type=idp&idpId=…) now completes instead of hanging: the console /login
// endpoint ignores redirectUri and lands the browser on the portal (so the
// loopback callback never fires), whereas the canonical IAM authorize endpoint
// honors redirectUri and issues the code to it.
//
// Returns ("", nil) when the link carries no idpId — "no hint" is a valid
// outcome (the caller runs plain pkce against the canonical endpoint). Returns
// an error only when ssoURL is not a valid absolute URL.
func extractIdpHint(ssoURL string) (string, error) {
	u, err := url.Parse(ssoURL)
	if err != nil || u == nil || u.Scheme == "" || u.Host == "" {
		return "", fmt.Errorf("sso URL is not valid: %q", ssoURL)
	}
	return u.Query().Get("idpId"), nil
}
